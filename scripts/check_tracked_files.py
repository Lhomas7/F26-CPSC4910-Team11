"""Reject tracked local artifacts, including files force-added past .gitignore."""

from pathlib import Path, PurePosixPath
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
LOCAL_DIRECTORIES = {
    'venv', '.venv', 'env', 'node_modules', '__pycache__', '.local-backups',
    '.pytest_cache', '.mypy_cache', '.ruff_cache', '.npm-cache',
}
LOCAL_PREFIXES = ('backend/media/', 'frontend/build/', 'htmlcov/', 'coverage/', 'logs/')
DATABASE_FILE = re.compile(r'\.(?:sqlite3?|db)(?:-(?:wal|shm|journal))?(?:\..*)?$', re.IGNORECASE)


def rejection_reason(filename):
    path = PurePosixPath(filename.replace('\\', '/'))
    name = path.name.lower()
    parts = [part.lower() for part in path.parts]
    if name == '.env' or name.startswith('.env.'):
        # A template remains subject to the independent content-based secret scan.
        template = name == '.env.example' or (name.startswith('.env.') and name.endswith('.example'))
        if not template:
            return 'environment file; only .env example templates belong in Git'
    if any(part in LOCAL_DIRECTORIES for part in parts[:-1]):
        return 'local dependency, cache, virtual environment, or database backup directory'
    normalized = '/'.join(parts)
    if normalized.startswith(LOCAL_PREFIXES):
        return 'generated output, uploaded media, or local logs'
    if DATABASE_FILE.search(name):
        return 'local database, archive, or SQLite journal sidecar'
    if name.endswith(('.pyc', '.pyo', '.bak', '.log')) or name == '.coverage':
        return 'generated bytecode, backup, log, or coverage data'
    return None


def tracked_paths(repository):
    result = subprocess.run(
        ['git', '-C', str(repository), 'ls-files', '--cached', '--full-name', '-z'],
        capture_output=True, check=False,
    )
    if result.returncode:
        raise RuntimeError('Could not read the Git index; run this command in a valid repository.')
    return [value.decode('utf-8', errors='surrogateescape') for value in result.stdout.split(b'\0') if value]


def main(repository=ROOT):
    try:
        violations = [(path, rejection_reason(path)) for path in tracked_paths(repository)]
    except (OSError, RuntimeError) as error:
        print(f'Tracked-file guard failed: {error}', file=sys.stderr)
        return 2
    violations = [(path, reason) for path, reason in violations if reason]
    if violations:
        print('Local-only files are tracked by Git:', file=sys.stderr)
        for path, reason in violations:
            # Escape control characters in filenames; never print file contents.
            print(f'  {path!r}: {reason}', file=sys.stderr)
        print('Remove these paths from the Git index while keeping needed local copies, then commit the removals. If secrets were exposed, rotate them; untracking does not erase history.', file=sys.stderr)
        return 1
    print('Tracked-file guard passed.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
